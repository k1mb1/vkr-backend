package com.github.k1mb1.vkr_backend.grading;

/**
 * Режим допуска конкретного задания: используется ли оно как барьер (гейт) для итоговой оценки.
 * <ul>
 *   <li>{@code NONE} — задание не влияет на допуск (по умолчанию).</li>
 *   <li>{@code PASS_FAIL} — бинарный гейт: сдано / не сдано (достаточно наличия оценки).
 *       Если не сдано — итогового вердикта нет вообще (например, «не зачтено»).</li>
 *   <li>{@code MIN_SCORE} — нужно набрать не менее {@code admissionMinScore} баллов за задание.
 *       Не набрал — нет вердикта.</li>
 *   <li>{@code TIERED} — уровневая система: каждому ярлыку итоговой оценки («5», «4», «3»…)
 *       соответствует свой минимум за это задание. Студент получает максимум ту оценку,
 *       чей tier он закрыл (и все младшие). Tiers хранятся по убыванию старшинства.</li>
 * </ul>
 */
public enum AssignmentAdmissionMode {
    NONE,
    PASS_FAIL,
    MIN_SCORE,
    TIERED,
}
